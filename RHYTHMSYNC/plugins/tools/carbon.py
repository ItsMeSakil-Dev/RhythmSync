import os

from pyrogram import filters
from pyrogram.types import Message
from config import BANNED_USERS
from RHYTHMSYNC import app, Carbon
from RHYTHMSYNC.utils.decorators.language import language
from RHYTHMSYNC.platforms.Carbon import UnableToFetchCarbon


@app.on_message(filters.command(["carbon", "cb"], prefixes=["/"]) & ~BANNED_USERS)
@language
async def carbon_cmd(client, message: Message, _):
    if message.reply_to_message and message.reply_to_message.text:
        code = message.reply_to_message.text
    elif len(message.command) > 1:
        code = message.text.split(None, 1)[1]
    else:
        return await message.reply_text(
            "**Usage:**\n"
            "• `/carbon <code>`\n"
            "• ya kisi text message pe reply karke `/carbon`"
        )

    status = await message.reply_text("`Generating carbon image...`")

    try:
        path = await Carbon.generate(code, message.from_user.id)
    except UnableToFetchCarbon as e:
        return await status.edit_text(f"**Failed:** `{e}`")
    except Exception as e:
        return await status.edit_text(f"**Error:** `{type(e).__name__}: {e}`")

    try:
        await message.reply_photo(path, caption=f"**Generated by {app.mention}**")
        await status.delete()
    finally:
        try:
            os.remove(path)
        except OSError:
            pass

